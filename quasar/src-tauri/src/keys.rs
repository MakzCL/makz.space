/// Our label to an enigo key, for macro playback and remapping.
pub fn to_enigo(label: &str) -> Option<enigo::Key> {
    use enigo::Key as E;
    Some(match label {
        "Esc" => E::Escape,
        "Enter" => E::Return,
        "Tab" => E::Tab,
        "Space" => E::Space,
        "Backspace" => E::Backspace,
        "Del" => E::Delete,
        "Home" => E::Home,
        "End" => E::End,
        "PgUp" => E::PageUp,
        "PgDn" => E::PageDown,
        "Up" => E::UpArrow,
        "Down" => E::DownArrow,
        "Left" => E::LeftArrow,
        "Right" => E::RightArrow,
        "LShift" | "RShift" | "Shift" => E::Shift,
        "LCtrl" | "RCtrl" | "Ctrl" => E::Control,
        "LAlt" | "RAlt" | "Alt" => E::Alt,
        "Win" | "Meta" => E::Meta,
        "Caps" => E::CapsLock,
        "F1" => E::F1,
        "F2" => E::F2,
        "F3" => E::F3,
        "F4" => E::F4,
        "F5" => E::F5,
        "F6" => E::F6,
        "F7" => E::F7,
        "F8" => E::F8,
        "F9" => E::F9,
        "F10" => E::F10,
        "F11" => E::F11,
        "F12" => E::F12,
        "F13" => E::F13,
        "F14" => E::F14,
        "F15" => E::F15,
        "F16" => E::F16,
        "F17" => E::F17,
        "F18" => E::F18,
        "F19" => E::F19,
        "F20" => E::F20,
        "volume-up" => E::VolumeUp,
        "volume-down" => E::VolumeDown,
        "mute" => E::VolumeMute,
        "play-pause" => E::MediaPlayPause,
        "next" => E::MediaNextTrack,
        "previous" => E::MediaPrevTrack,
        s if s.chars().count() == 1 => E::Unicode(s.chars().next()?.to_ascii_lowercase()),
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn round_trip_common_keys() {
        for k in [rdev::Key::KeyW, rdev::Key::Escape, rdev::Key::F5, rdev::Key::Space] {
            let l = super::labels(&k)[0];
            assert!(super::to_enigo(l).is_some(), "{l}");
        }
    }
}
