// Sparks UI: challenge grid, claim animation (sparks fly, balance counts up), header balance, server boost bar.
const { chromium } = require('playwright'); const { execSync } = require('child_process');
const BASE = process.argv[2] ?? 'http://localhost:3900', OUT = process.argv[3] ?? '.';
const DB = process.env.E2E_DB ?? 'postgres://syndo:syndo@localhost:5432/syndo_e2e';
const SFX = Date.now().toString(36).slice(-5); const results = [];
const check = (n, ok, x = '') => { results.push({ ok: !!ok }); console.log(`${ok ? 'PASS' : 'FAIL'} ${n} ${x}`); };
const seen = (l, ms = 6000) => l.waitFor({ state: 'visible', timeout: ms }).then(() => true, () => false);
(async () => {
  const b = await chromium.launch(); const c = await b.newContext({ viewport: { width: 1440, height: 950 } });
  await c.addInitScript(() => { try { localStorage.setItem('send.whatsNew.seen', 'skip'); localStorage.setItem('send.desktop-prompt.dismissed.v1', '1'); } catch {} });
  const p = await c.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  const api = (m, path, body) => p.evaluate(async ([m, path, body]) => { const r = await fetch(path, { method: m, headers: body ? { 'content-type': 'application/json', 'x-send-client': '1' } : { 'x-send-client': '1' }, body: body ? JSON.stringify(body) : undefined }); return { status: r.status, body: await r.json().catch(() => null) }; }, [m, path, body]);
  await p.goto(BASE + '/login');
  const me = (await api('POST', '/api/auth/register', { email: `su_${SFX}@example.test`, username: `su_${SFX}`, password: 'correct horse battery' })).body.user;
  execSync(`psql ${DB} -qc "update users set avatar_key='avatars/x/a.webp', banner_key='banners/x/b.webp', bio='hello' where id=${me.id}"`);
  const g = (await api('POST', '/api/guilds', { name: 'Bar Lab' })).body;
  check('Server owners can turn on the boost bar', (await api('PATCH', `/api/guilds/${g.id}`, { show_boost_bar: true })).status === 200);
  await p.goto(`${BASE}/channels/${g.id}`);
  const bar = p.locator('.server-boost-bar');
  check('Boost bar shows under the server name', await seen(bar, 10000) && /0 boosts/.test(await bar.textContent()), await bar.textContent().catch(() => ''));
  await p.locator('.side-h, .guild-h').first().screenshot({ path: `${OUT}/boostbar-head.png` }).catch(() => {});
  await p.screenshot({ path: `${OUT}/boostbar.png`, clip: { x: 60, y: 0, width: 320, height: 220 } });
  await p.evaluate(() => window.dispatchEvent(new CustomEvent('send:dialog', { detail: { kind: 'userSettings', tab: 'boosts' } })));
  const wallet = p.locator('.boost-wallet');
  await seen(p.locator('.wallet-sparks'), 8000);
  check('Balance at the top right shows boosts and Sparks', await seen(wallet, 8000) && /0 boosts/.test(await wallet.textContent()) && /0 Sparks/.test(await wallet.textContent()), await wallet.textContent().catch(() => ''));
  const cols = await p.locator('.challenges').evaluate((e) => getComputedStyle(e).gridTemplateColumns.split(' ').length);
  check('Challenges are in a 3-column grid', cols === 3, `${cols} columns`);
  const ready = p.locator('.challenge.ready .challenge-claim').first();
  check('Profile challenge is ready to claim', await seen(ready, 6000));
  await p.locator('.sparks').scrollIntoViewIfNeeded();
  await ready.click();
  const flew = await p.waitForSelector('.spark-fly', { state: 'attached', timeout: 3000 }).then(() => true, () => false);
  await p.waitForTimeout(450); await p.screenshot({ path: `${OUT}/claim-fly.png` });
  check('Sparks fly from the button when claiming', flew);
  const mid = await wallet.textContent();
  await p.waitForTimeout(2200);
  const end = await wallet.textContent();
  check('Balance counts up to 100', /100 Sparks/.test(end) && (await p.locator('.sparks h3').textContent()).includes('100'), `mid: ${mid} end: ${end}`);
  await p.locator('.sparks').screenshot({ path: `${OUT}/sparks-grid.png` });
  check('No page errors', !errs.length, errs.join(' | '));
  await b.close(); const f = results.filter((r) => !r.ok).length; console.log(`\n${results.length - f}/${results.length} passed`); process.exit(f ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
